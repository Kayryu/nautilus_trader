/// Expected terms for one perpetual TP/SL position update.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DeepXPerpPointUpdateExpected {
    /// Exact runtime call arguments.
    pub params: DeepXPerpProfitAndLossPointParams,
    /// Index of the signed extrinsic in the block.
    pub extrinsic_index: u32,
}

/// Expected terms for an order generated by a perpetual close call.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DeepXPerpCloseExpected {
    /// Exact runtime call arguments.
    pub params: DeepXPerpCloseParams,
    /// Block number used by the runtime as order creation time.
    pub block_number: u64,
    /// Index of the signed extrinsic in the block.
    pub extrinsic_index: u32,
}

/// Outcome established from indexed dispatch and perpetual business events.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DeepXPerpPositionInclusionOutcome {
    /// Dispatch succeeded and the expected event was emitted.
    Success,
    /// Dispatch failed without applying the operation.
    Failed,
}

/// Indexed inclusion evidence for a perpetual position operation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DeepXPerpPositionInclusionEvidence {
    /// Index of the signed extrinsic in the block.
    pub extrinsic_index: u32,
    /// Authoritative inclusion outcome at that index.
    pub outcome: DeepXPerpPositionInclusionOutcome,
}

/// Errors while binding complete runtime events to a perpetual position operation.
#[derive(Debug, Error)]
pub enum DeepXPerpPositionEventError {
    /// Required runtime events are absent from the approved interface.
    #[error(transparent)]
    RuntimeInterface(#[from] DeepXRuntimeInterfaceError),
    /// SCALE decoding failed against the supplied metadata.
    #[error("unable to decode DeepX perpetual position events: {0}")]
    Decode(#[source] Box<subxt_core::Error>),
    /// Event storage is incomplete, or no dispatch event exists at the target index.
    #[error("incomplete DeepX perpetual position event storage")]
    MalformedEventBytes,
    /// Runtime state does not match the expected operation terms.
    #[error("DeepX perpetual position event conflicts with expected terms")]
    ConflictingEvent,
    /// Dispatch or business event was emitted more than once at the target index.
    #[error("duplicate DeepX perpetual position event")]
    DuplicateEvent,
    /// Successful dispatch did not emit the expected event.
    #[error("successful DeepX perpetual position operation has no matching business event")]
    MissingBusinessEvent,
    /// A failed dispatch also emitted the expected event.
    #[error("failed DeepX perpetual position operation conflicts with a business event")]
    ConflictingBusinessEvent,
}

/// Verifies a TP/SL update against complete `System.Events` storage.
///
/// A zero input point must be represented by `None` in the position event. Only position fields
/// established by the call arguments are compared. The caller verifies the signed operation and
/// block canonicality.
///
/// # Errors
///
/// Returns an error for incomplete, duplicate, or conflicting indexed events.
pub fn decode_perp_point_update_inclusion(
    interfaces: &DeepXRuntimeInterfaceCatalog,
    metadata: &Metadata,
    expected: DeepXPerpPointUpdateExpected,
    event_bytes: &[u8],
) -> Result<DeepXPerpPositionInclusionEvidence, DeepXPerpPositionEventError> {
    decode_indexed_perp_inclusion(
        interfaces,
        metadata,
        expected.extrinsic_index,
        event_bytes,
        "PositionUpdated",
        |fields| point_update_fields_match(fields, expected.params),
    )
}

/// Verifies an order generated by a close call against complete `System.Events` storage.
///
/// Position-derived direction and size are checked for consistency but cannot be inferred from
/// the close call. The generated order ID is independent of the signed extrinsic's nonce. The
/// caller verifies the signed operation and block canonicality.
///
/// # Errors
///
/// Returns an error for incomplete, duplicate, or conflicting indexed events.
pub fn decode_perp_close_inclusion(
    interfaces: &DeepXRuntimeInterfaceCatalog,
    metadata: &Metadata,
    expected: DeepXPerpCloseExpected,
    event_bytes: &[u8],
) -> Result<DeepXPerpPositionInclusionEvidence, DeepXPerpPositionEventError> {
    decode_indexed_perp_inclusion(
        interfaces,
        metadata,
        expected.extrinsic_index,
        event_bytes,
        "OrderPlaced",
        |fields| close_order_fields_match(fields, expected),
    )
}

fn decode_indexed_perp_inclusion(
    interfaces: &DeepXRuntimeInterfaceCatalog,
    metadata: &Metadata,
    extrinsic_index: u32,
    event_bytes: &[u8],
    event_name: &str,
    fields_match: impl Fn(&Composite<u32>) -> bool,
) -> Result<DeepXPerpPositionInclusionEvidence, DeepXPerpPositionEventError> {
    use DeepXPerpPositionEventError as Error;

    interfaces.event("PerpMarket", event_name)?;
    interfaces.event("System", "ExtrinsicSuccess")?;
    interfaces.event("System", "ExtrinsicFailed")?;
    let mut remaining = event_bytes;
    let declared = Compact::<u32>::decode(&mut remaining)
        .map_err(|_| Error::MalformedEventBytes)?
        .0;
    let mut consumed = event_bytes.len() - remaining.len();
    let mut count = 0_u32;
    let mut dispatch = None;
    let mut matched = false;
    let events = Events::<DeepXRuntimeConfig>::decode_from(event_bytes.to_vec(), metadata.clone());
    for event in events.iter() {
        let event = event.map_err(|e| Error::Decode(Box::new(e)))?;
        count = count.checked_add(1).ok_or(Error::MalformedEventBytes)?;
        consumed = consumed
            .checked_add(event.bytes().len())
            .ok_or(Error::MalformedEventBytes)?;
        if event.phase() != Phase::ApplyExtrinsic(extrinsic_index) {
            continue;
        }
        if event.pallet_name() == "System" {
            let outcome = match event.variant_name() {
                "ExtrinsicSuccess" => DeepXPerpPositionInclusionOutcome::Success,
                "ExtrinsicFailed" => DeepXPerpPositionInclusionOutcome::Failed,
                _ => continue,
            };
            if dispatch.replace(outcome).is_some() {
                return Err(Error::DuplicateEvent);
            }
        } else if event.pallet_name() == "PerpMarket" && event.variant_name() == event_name {
            let fields = event
                .field_values()
                .map_err(|e| Error::Decode(Box::new(e)))?;
            if !fields_match(&fields) {
                return Err(Error::ConflictingEvent);
            }
            if matched {
                return Err(Error::DuplicateEvent);
            }
            matched = true;
        }
    }
    if count != declared || consumed != event_bytes.len() {
        return Err(Error::MalformedEventBytes);
    }
    let outcome = match (dispatch.ok_or(Error::MalformedEventBytes)?, matched) {
        (DeepXPerpPositionInclusionOutcome::Success, true) => {
            DeepXPerpPositionInclusionOutcome::Success
        }
        (DeepXPerpPositionInclusionOutcome::Failed, false) => {
            DeepXPerpPositionInclusionOutcome::Failed
        }
        (DeepXPerpPositionInclusionOutcome::Success, false) => {
            return Err(Error::MissingBusinessEvent);
        }
        (DeepXPerpPositionInclusionOutcome::Failed, true) => {
            return Err(Error::ConflictingBusinessEvent);
        }
    };
    Ok(DeepXPerpPositionInclusionEvidence {
        extrinsic_index,
        outcome,
    })
}

fn point_update_fields_match(
    fields: &Composite<u32>,
    params: DeepXPerpProfitAndLossPointParams,
) -> bool {
    let Composite::Named(fields) = fields else {
        return false;
    };
    let field = |name| {
        fields
            .iter()
            .find_map(|(key, value)| (key == name).then_some(value))
    };
    if fields.len() != 4
        || field("owner").and_then(decode_event_bytes).as_deref()
            != Some(params.subaccount.as_slice())
        || field("market_id").and_then(ScaleValue::as_u128) != Some(u128::from(params.market_id))
        || field("pnl").and_then(ScaleValue::as_i128) != Some(0)
    {
        return false;
    }
    let Some(ScaleValue {
        value: ValueDef::Composite(Composite::Named(pos)),
        ..
    }) = field("pos")
    else {
        return false;
    };
    let field = |name| {
        pos.iter()
            .find_map(|(key, value)| (key == name).then_some(value))
    };
    field("owner").and_then(decode_event_bytes).as_deref() == Some(params.subaccount.as_slice())
        && field("market_id").and_then(ScaleValue::as_u128) == Some(u128::from(params.market_id))
        && field("take_profit").is_some_and(|value| {
            value_matches_optional_u128(
                value,
                (params.take_profit_point != 0).then_some(params.take_profit_point),
            )
        })
        && field("stop_loss").is_some_and(|value| {
            value_matches_optional_u128(
                value,
                (params.stop_loss_point != 0).then_some(params.stop_loss_point),
            )
        })
}

fn close_order_fields_match(fields: &Composite<u32>, expected: DeepXPerpCloseExpected) -> bool {
    let Composite::Named(outer) = fields else {
        return false;
    };
    let field = |name| {
        outer
            .iter()
            .find_map(|(key, value)| (key == name).then_some(value))
    };
    let Some(order_id) = field("order_id")
        .and_then(ScaleValue::as_u128)
        .filter(|id| *id <= u128::from(u64::MAX))
    else {
        return false;
    };
    let Some(ScaleValue {
        value: ValueDef::Composite(Composite::Named(order)),
        ..
    }) = field("order")
    else {
        return false;
    };
    let field = |name| {
        order
            .iter()
            .find_map(|(key, value)| (key == name).then_some(value))
    };
    let Some(is_long) = field("is_long").and_then(ScaleValue::as_bool) else {
        return false;
    };
    let Some(size) = field("size")
        .and_then(ScaleValue::as_u128)
        .filter(|size| *size > 0)
    else {
        return false;
    };
    let Some(leverage) = field("leverage")
        .and_then(ScaleValue::as_u128)
        .filter(|leverage| *leverage > 0)
    else {
        return false;
    };
    let params = expected.params;
    outer.len() == 2 && order.len() == 16
        && field("order_id").and_then(ScaleValue::as_u128) == Some(order_id)
        && field("owner").and_then(decode_event_bytes).as_deref() == Some(params.subaccount.as_slice())
        && field("market_id").and_then(ScaleValue::as_u128) == Some(u128::from(params.market_id))
        && field("is_long").and_then(ScaleValue::as_bool) == Some(is_long)
        && field("size").and_then(ScaleValue::as_u128) == Some(size)
        && field("size_remain").and_then(ScaleValue::as_u128) == Some(size)
        && field("size_filled").and_then(ScaleValue::as_u128) == Some(0)
        && field("create_time").and_then(ScaleValue::as_u128) == Some(u128::from(expected.block_number))
        && field("leverage").and_then(ScaleValue::as_u128) == Some(leverage)
        && field("price").and_then(ScaleValue::as_u128).is_some_and(|actual| params.price == 0 || actual == params.price)
        && field("order_type").is_some_and(|value| if params.price == 0 {
            value_matches_order_type(value, DeepXSpotOrderType::Market(params.slippage))
        } else {
            matches!(&value.value, ValueDef::Variant(variant) if variant.name == "Stop" && variant.values.values().next().is_none())
        })
        && field("status").is_some_and(|value| matches!(&value.value, ValueDef::Variant(variant) if variant.name == "Open" && variant.values.values().next().is_none()))
        && field("reduce_only").and_then(ScaleValue::as_bool) == Some(true)
        && field("post_only").is_some_and(|value| value_matches_post_only(value, DeepXPostOnlyParam::None))
        && field("take_profit").is_some_and(|value| value_matches_optional_u128(value, None))
        && field("stop_loss").is_some_and(|value| value_matches_optional_u128(value, None))
}

fn value_matches_optional_u128(value: &ScaleValue<u32>, expected: Option<u128>) -> bool {
    let ValueDef::Variant(variant) = &value.value else {
        return false;
    };
    let values: Vec<_> = variant.values.values().collect();
    match expected {
        None => variant.name == "None" && values.is_empty(),
        Some(expected) => {
            variant.name == "Some" && values.len() == 1 && values[0].as_u128() == Some(expected)
        }
    }
}

